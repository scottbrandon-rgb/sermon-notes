// Bundles content/sermons/*.md into netlify/functions/lib/seed.mjs so the site
// ships with real sermons and the functions need no filesystem access at runtime.
// Sermons published through /admin are stored separately (Netlify Blobs) and
// override a seed with the same date.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseSermon, validateSermon, sermonMeta } from '../src/lib/parse.js';
import { defaultGoLive } from '../src/lib/time.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dir = join(root, 'content', 'sermons');
const out = join(root, 'netlify', 'functions', 'lib', 'seed.mjs');

const seeds = [];
for (const file of readdirSync(dir).filter((f) => f.endsWith('.md')).sort()) {
  const markdown = readFileSync(join(dir, file), 'utf8');
  const doc = parseSermon(markdown);
  const { errors } = validateSermon(doc);
  if (errors.length) {
    console.error(`\n${file} has problems:\n - ${errors.join('\n - ')}\n`);
    process.exit(1);
  }
  const meta = sermonMeta(doc);
  seeds.push({ ...meta, publishAt: defaultGoLive(meta.date).toISOString(), markdown });
}

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, '// Generated by scripts/build-seed.mjs. Do not edit.\nexport default ' + JSON.stringify(seeds, null, 2) + ';\n');
console.log(`Bundled ${seeds.length} sermon${seeds.length === 1 ? '' : 's'} from content/sermons.`);
